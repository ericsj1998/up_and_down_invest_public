/**
 * 차트에 **무엇을 그려도 되나** — `update()` 가 뒤로 못 가는 규칙 (2026-08-30 사고).
 *
 * 🔴 실제 오류:
 *
 *     Cannot update oldest data, last time=[object Object], new time=[object Object]
 *
 * lightweight-charts 의 `series.update(bar)` 는 **시리즈가 들고 있는 마지막 값보다
 * 과거**를 받으면 던진다. 그리고 그 예외가 렌더 중에 나므로, 경계가 없던 동안에는
 * 화면이 통째로 사라졌다 — 사용자가 본 흰 화면이 이것이다.
 *
 * ## 왜 옛 가드가 못 잡았나
 *
 * 비교 대상이 **props**(`frame.candles.at(-1)`)였다. 그런데 `update` 가 보는 것은
 * **시리즈에 실제로 들어간 값**이다. 축을 바꾸는 순간 둘이 갈린다:
 *
 *     1m 을 보다가 4h 로 바꾼다
 *     → 시리즈는 4h 로 다시 그려지는데 `forming` 은 아직 1m 조각(18:03)이다
 *     → props 의 마지막은 4h 봉(16:00) 이라 `18:03 < 16:00` 이 거짓 → 통과
 *     → 시리즈에 18:03 이 박힌다
 *     → 곧 진짜 4h 조각(16:00)이 오면 시리즈의 마지막보다 과거라 **터진다**
 *
 * ⇒ 판정을 순수 함수로 떼어 시험이 이 순서를 그대로 재현한다.
 */

/**
 * 이 시각의 조각을 그려도 되나.
 *
 * @param painted 차트에 **실제로 들어간** 마지막 시각(초). 아직 없으면 `null`.
 * @param at 그리려는 조각의 시각(초).
 * @returns 그려도 되면 참.
 *
 * ⚠️ **같은 시각은 허용한다.** 만들어지는 중인 봉을 갱신하는 것이 정상 경로이고,
 * 그것을 막으면 꼬리가 안 흔들린다.
 */
export function mayPaint(painted: number | null, at: number): boolean {
  if (painted === null) return true;
  return at >= painted;
}

/**
 * 시리즈를 **통째로 다시 그린 뒤**, 만들어지던 봉을 도로 얹어도 되나.
 *
 * @param lastClosed 방금 넣은 **마감 봉들**의 마지막 시각(초). 없으면 `null`.
 * @param at 얹으려는 진행 중 봉의 시각(초).
 * @returns 얹어도 되면 참.
 *
 * 🔴 **`mayPaint` 와 규칙이 다르다 — 같은 시각을 허용하지 않는다.** 그 한 글자가
 * 사용자가 본 증상이었다 (2026-08-30: *"띡 사라지고 봉 생기고 다시 꼬리 생기고"*).
 *
 * ## 왜 같으면 안 되나
 *
 * 10초봉에서 시각 100 의 봉이 만들어지는 동안, 화면은 1초마다 그 봉을 갱신한다
 * (`mayPaint` 가 같은 시각을 허용하는 이유다 — 꼬리가 자라는 정상 경로다).
 *
 * 그러다 구조물 폴링이 돌아오면 이제 **100 이 마감 봉으로** 들어 있다. 그 마감 봉이
 * **최종본**이고, 고가·저가가 그 봉의 진짜 끝값이다. 그런데 같은 시각을 허용하면
 * 그 위에 **손에 들고 있던 진행 중 스냅샷**을 덮어썼다 — 그 스냅샷은 봉이 끝나기
 * 전에 찍힌 것이라 **고가가 더 낮다.**
 *
 *     마감 봉 100    고 78047.7   ← 진짜 끝값
 *     들고 있던 조각  고 78047.6   ← 0.4초 전에 찍힌 것
 *     → 덮어쓰면 꼬리가 **줄어든다**. 다음 틱에 다시 자란다. 이것이 깜빡임이다.
 *
 * ⇒ 마감 봉이 이미 그 시각을 들고 있으면 **손대지 않는다.** 마감된 값이 사실이다.
 */
export function mayReplant(lastClosed: number | null, at: number): boolean {
  if (lastClosed === null) return true;
  return at > lastClosed;
}
