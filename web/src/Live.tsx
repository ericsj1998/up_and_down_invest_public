/**
 * 라이브 단추 — **축 단추 줄 오른쪽 끝**에 선다 (사용자 요구 2026-08-30).
 *
 * > *"이 타임라인에서 가장 오른쪽에 버튼 위치시켜줘. 그리고 라이브 버튼은 on off 여서,
 * > 라이브가 켜져있을 때는 오른쪽은 항상 최신 기준으로 맞춰지는 거구."*
 *
 * 🔴 **켜고 끄는 스위치다.** 처음 되살렸을 때는 *"지금 붙어 있나"* 를 스크롤 위치에서
 * **읽기만** 했고, 누르면 최신으로 가는 단추였다 — 그러면 확대 한 번에 추종이 조용히
 * 꺼지고 그 뒤로 새 봉이 화면 밖에 쌓인다. 사람은 차트가 멈춘 줄 안다.
 *
 * ⇒ 사람이 켜고 끈다. 켜져 있는 동안에는 **무엇을 해도** 오른쪽 끝이 안 풀린다
 * (줌·축 조절 포함) — 그 고정은 `Chart` 가 한다.
 *
 * ⚠️ 상태가 **부모**에 있는 이유: 이 단추가 축 단추 줄에 서야 하는데 그 줄은 차트 밖에
 * 있다. 차트 안에 두면 단추가 차트 아래로 밀린다.
 *
 * ## 🔴 이 단추는 **보는 자리**만 정한다 (2026-08-30 에 두 번 헷갈렸다)
 *
 * 한때 여기에 *"새 봉을 받는다"* 는 뜻까지 묶었다가 되돌렸다. 묶어 놓고 이 단추를
 * 기본 꺼짐으로 만들었더니 **열자마자 멈춘 그림**이 됐다 (사용자 신고: *"10초봉
 * 보고있는데 계속 멈춰있어"*).
 *
 * ⇒ 둘은 다른 것이다:
 *
 *       이 단추   보는 자리 — 오른쪽 끝에 붙을 것인가
 *       폴링      받는 것   — 새 봉을 받을 것인가 (화면이 알아서 한다)
 *
 * ⛔ **과거를 보려고 껐다고 데이터가 멈춰야 할 이유는 없다.** 껐다 켜면 그동안 쌓인
 * 최신 봉으로 곧바로 붙는다.
 */

type Props = {
  on: boolean;
  onToggle: () => void;
};

export function Live({ on, onToggle }: Props) {
  return (
    <button
      className={on ? "btn small primary" : "btn small"}
      onClick={onToggle}
      // ⭐ **왼쪽 여백을 밀어 오른쪽 끝으로 보낸다** — 줄에 축이 몇 개든 항상 끝이다.
      style={{ marginLeft: "auto" }}
      title={
        on
          ? "라이브 — 줌·축을 바꿔도 오른쪽 끝은 최신 봉에 붙어 있다. 누르면 끈다"
          : "라이브가 꺼져 있다 — 새 봉은 계속 받지만 보는 자리는 안 따라간다 (과거를 보는 중). 누르면 켠다"
      }
    >
      {on ? "● 라이브" : "○ 라이브 꺼짐"}
    </button>
  );
}
