"""구조물 계산의 Decimal 컨텍스트 고정 (P1-1 · 원칙 P1, 절대 규칙 #5).

## 왜 필요한가

Decimal 의 `+ - * /` 와 `quantize` 는 **주변 컨텍스트**(`getcontext()`)의 정밀도를 쓴다.
호출자가 컨텍스트를 좁혀 놓으면 같은 입력에서 다른 값이 나오고, 심하면
`InvalidOperation` 으로 죽는다. "동일 입력 → 동일 출력"(절대 규칙 #5)이 호출 환경에
의존하면 안 되므로, 순수 계산 진입점마다 컨텍스트를 고정한다.

이것은 이론적 우려가 아니다 — P1-1 개발 중 `prec=6` 컨텍스트에서 추세선 계산이
실제로 죽었고, 그 테스트가 이 모듈을 만들게 했다.

## 왜 진입점에서 한 번인가

연산마다 `ctx.multiply(...)` 를 쓰면 정확하지만 식이 읽히지 않는다. **공개 함수 본문
전체를 감싸면** 그 안의 모든 연산이 자동으로 고정 컨텍스트를 쓰고, 코드는 평범한
`a + b * c` 로 남는다. 새 연산을 추가할 때 고정을 잊는 경로도 생기지 않는다.

## 왜 prec=34 인가

IEEE 754 decimal128 의 정밀도다. 원화 가격은 1e9 규모에 소수 8자리까지 쓰므로 17자리면
충분하고, 34자리는 중간 계산(기울기 곱 봉 수)의 누적에도 여유가 있다.
"""

from decimal import Context, Decimal, InvalidOperation, localcontext

DECIMAL_CONTEXT = Context(prec=34)
"""구조물 계산 전용 고정 컨텍스트 (IEEE 754 decimal128 정밀도)."""


def fixed_context():
    """고정 컨텍스트 블록을 만든다.

    Returns:
        `with` 문에 쓸 컨텍스트 매니저.

    Note:
        공개 계산 함수는 본문 전체를 이것으로 감싼다. 감싸지 않은 함수는 호출자의
        컨텍스트에 결과가 좌우된다.
    """
    return localcontext(DECIMAL_CONTEXT)


def zero(text: object) -> bool:
    """이 값이 **0 인가** — 거래소가 준 문자열을 숫자로 읽는다 (2026-08-30 사고).

    Args:
        text: 거래소 응답의 수량 필드. `None` 이나 빈 문자열은 0 으로 본다.

    Returns:
        0 이면 참. 숫자로 읽을 수 없으면 **거짓** — 모르는 값을 "없다" 로 읽으면
        있는 포지션을 놓친다.

    Note:
        🔴 **문자열 비교로 하다가 요율 한도를 태웠다.** `in {"0", "0.0"}` 으로 걸렀는데
        거래소는 같은 0 을 여러 모양으로 준다. Binance 무기한 실측 (734행):

            "0"       481      ← 걸렸다
            "0.0"     146      ← 걸렸다
            "0.00"     64      ⛔ 안 걸렸다
            "0.000"    38      ⛔
            "0.0000"    3      ⛔
            "0E-7"      1      ⛔

        **107행이 "열려 있는 포지션" 으로 샜다.** 콘솔은 그 107개(분기물·주식 토큰까지)
        의 계약 명세를 매번 물었고, testnet 에 없는 심볼이라 전부 실패했다. 실패는
        캐시하지 않으므로(그것은 옳다) **영원히 반복**됐다 — 실측 5분에 `exchangeInfo`
        224회, 그것만으로 요율의 상당 부분이었다.

        ⚠️ 고친 곳이 여섯이었다. 같은 판단을 여섯 벌로 쓰고 있었고, 그래서 한 번에
        여섯 곳이 틀렸다.

        ⛔ **숫자로 못 읽으면 거짓을 낸다.** "0 이다" 라고 답하면 그 포지션은 화면에서
        사라지고, 사라진 포지션은 아무도 안 닫는다 (절대 규칙 #8 과 같은 방향).
    """
    if text is None:
        return True
    raw = str(text).strip()
    if not raw:
        return True
    try:
        return Decimal(raw) == 0
    except (InvalidOperation, ValueError):
        return False
