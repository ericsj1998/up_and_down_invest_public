    @property
    def attribution(self) -> str:
        """성과를 가르는 키 — `sample_ma_cross@0.1.0`."""
        return f"{self.playbook_id}@{self.version}"

    def runs_in(
        self,
        *,
        market_group: MarketGroup,
        timeframe: Timeframe,
        trend: TrendDirection | None,
        has_box: bool,
    ) -> bool:
        """지금 이 자리에서 이 플레이북이 도는가.

        Args:
            market_group: 종목의 운용 갈래.
            timeframe: 지금 시간축.
            trend: 상위 TF 주 추세.
            has_box: 유효한 박스가 있는가.

        Returns:
            돌면 True.

        Note:
            🔴 **국면이 안 맞으면 셋업이 나와도 후보가 아니다.** 이것이 이 층의 핵심
            효능이다 — 옛 구조에서는 `order_block` 이 나오면 국면과 무관하게 후보였고,
            그래서 상승장의 눌림목과 횡보장의 왕복이 **한 줄에 섞여 기록**됐다.
        """
        if market_group not in self.market_groups or timeframe is not self.timeframe:
            return False
        return any(regime.matches(trend, has_box=has_box) for regime in self.regimes)
