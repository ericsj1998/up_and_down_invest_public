"""박스권 **매매 계획** — 진입 2다리 · 손절 · 익절 (playbooks.md 확정 3).

## 이 파일에 남은 것

레벨을 **찾는** 일은 `level_book` 이 한다. 여기는 찾은 레벨로 **계획을 만드는** 일만 한다.

```
level_book   레벨 생성 · 접점 누적 · 역할 계산   (창 없음)
여기         스마트 박스 · 호가 라운딩 · 손익 자료형
```

⚠️ 예전에는 이 파일이 창 기반으로 박스를 **직접 찾았다** (`detect_box`·`_boundaries`·
`_inner`·`draft_box`). 사용자 지적으로 폐기했다:

> *"그냥 전체에서 지지 저항에 닿았을 때 진입하는 건데 대체 왜 봉이 필요해?"*

창은 전략이 아니라 **봉마다 재계산하던 구현의 잔재**였다. 화면(200봉)과 셋업(80봉)이
다른 박스를 봐서 *"화면엔 그려지는데 진입은 안 한다"* 가 나온 것이 그 대가였다.
"""

