"""기본 손절 깊이 — 안전지대 한 배 아래. 확정 3 의 스마트 박스가 그 자리다."""


@dataclass(frozen=True, slots=True)
class BoxPlan:
    """박스권 한 판의 진입·손절·익절.

    Attributes:
        first: 1차 매수가 — 하단 레벨 상단.
        second: 2차 매수가 — 하단 레벨 하단 (축에 따라 더 아래).
        stop: 손절가 — 안전지대 아래.
        target: 익절가 — 상단 레벨 하단.

    Note:
        🔴 **이것은 제안이지 확정이 아니다.** 집행값의 SSoT 는 RiskManager 다
        (절대 규칙 #4). 수량·리스크는 `decision/` 이 정한다.

        ⚠️ `first > second` 다 — 지지에서는 위에서 내려오므로 첫 다리가 더 비싸다.
        순서는 **가격이 아니라 시간**이다.
    """

    first: Decimal
    second: Decimal
    stop: Decimal
    target: Decimal

    @property
    def average(self) -> Decimal:
        """2분할 균등 매수의 계획 평단."""
        return (self.first + self.second) / Decimal(2)

    @property
    def risk(self) -> Decimal:
        """계획 평단에서 손절까지 거리."""
        return self.average - self.stop

    @property
    def reward(self) -> Decimal:
        """계획 평단에서 익절까지 거리."""
        return self.target - self.average

    @property
    def rr(self) -> Decimal | None:
        """손익비. 손절 거리가 0 이면 None."""
        return None if self.risk <= 0 else self.reward / self.risk


def round_down(price: Decimal, tick: Decimal) -> Decimal:
    """호가 단위로 **내림**.

    Args:
        price: 원래 가격.
        tick: 호가 단위.

    Returns:
        내림한 가격.

    Note:
        🔴 **전부 내림이라 전부 보수적이다.**

        ```
        진입   더 싸게 사려는 값 -> 체결이 어려워진다   (기회 상실이지 손실이 아니다)
        손절   더 아래로        -> 손실을 크게 잡는다
        익절   더 일찍          -> 수익을 작게 잡는다
        ```

        올림·반올림을 섞으면 어느 쪽은 낙관이 된다. 방향을 하나로 고정해야 성과가
        라운딩 때문에 부풀지 않는다.

        ⭐ 공개 함수다. `level_book` 이 같은 라운딩을 써야 화면과 셋업이 같은 값을 낸다.
    """
    return (price / tick).to_integral_value(rounding="ROUND_FLOOR") * tick
