SPAN_COVER = Decimal(6)
"""박스 실효 폭이 왕복 비용의 이 배수는 되어야 **박스**다 (사용자 확정 2026-08-17).

🔴 **산수에서 나온 수다.** 반익 자리는 대략 폭의 절반 위이므로

```
반익반본 순익 = (폭/2)/2 - 비용 = 폭/4 - 비용
```

| 폭 | 반익반본 순익 | 뜻 |
|---|---|---|
| 4c | 0 | 반익이 겨우 본전 |
| **6c (0.94%)** | **0.5c ≈ 0.08%** | 반익이 확실히 양수 · 전량은 3c 를 넘는다 |
| 8c | 1.0c ≈ 0.16% | 반익이 왕복 수수료를 다 번다. 대신 표본이 준다 |

⚠️ 실측 실효 폭 **중앙값이 0.5%(약 3c)** 였고, 그래서 반익하면 0.09% 만 남아
*"계속 사고 팔고 사고 팔고"* 가 됐다 (사용자 지적).

⛔ 성과를 보고 올리지 않는다 (§5.6.2). 후보: 4 / 6 / 8.
"""


def box_span(price: Decimal, round_trip: Decimal, *, cover: Decimal = SPAN_COVER) -> Decimal:
    """박스로 인정할 **최소 실효 폭** (가격 단위).

    Args:
        price: 현재가.
        round_trip: 왕복 비용 비율.
        cover: 왕복 비용의 몇 배여야 박스인가 (T42 ⑤ 회전 축 · 후보 6/9/12). 기본은
            `SPAN_COVER` — 안 넘기는 호출자는 한 비트도 안 달라진다.

    Returns:
        `roles_at(min_span=)` 에 그대로 넘길 값.

    Note:
        🔴 **한 곳에서만 만든다.** 세 곳(`셋업`·`has_box`·`화면`)이 `roles_at` 을 각자
        부르면서 문턱을 **서로 다르게** 줬다 — 화면에는 실효 폭 0.28% 짜리 박스가
        그려지는데 셋업은 0.94% 미만을 버리고 있었다. 값을 함수로 묶어야 호출부가
        빠뜨릴 수 없다.

        ⛔ **상단 거리 조건(`min_gap`)은 없앴다** (사용자 확정 2026-08-17). 그것은
        *"익절이 비용도 못 갚는 상단은 상단이 아니다"* 라는 **롱 기준** 산수였는데,
        숏에게 상단은 **익절이 아니라 진입 자리**다. 실측에서 그 비대칭이 숏을
        거의 전멸시켰다 — 673봉 구간에서 롱 방아쇠 325 회 대 숏 방아쇠 **2 회**.

        ⭐ 대신 박스권 탐지기의 `_build` 가 **실제 체결가·방향 기준**으로 익절
        거리를 본다 (`COST_COVER`). 그쪽이 엄격하고 정확하므로 여기서 또 걸 이유가
        없었다 — 중복이자 편향이었다.
    """
    return price * round_trip * cover


